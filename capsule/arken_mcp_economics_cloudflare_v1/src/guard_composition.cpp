void detail::validateService(std::string_view id){const auto all=Services();C::Require(std::find(all.begin(),all.end(),id)!=all.end(),"budget_unknown_service");}
Json detail::manifest(const std::vector<Module>& modules){
 Json rows=Json::array();std::set<std::string> names;std::size_t total=0;
 C::Require(!modules.empty()&&modules.size()<=32,"budget_module_count");
 for(const auto& m:modules){
  C::Require(std::regex_match(m.name,std::regex("[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}"))&&m.name!="metadata"&&names.insert(m.name).second,"budget_module_name");
  C::Require(m.mediaType=="application/javascript+module"||m.mediaType=="application/wasm"||m.mediaType=="text/plain","budget_module_type");
  C::Require(!m.bytes.empty()&&m.bytes.size()<=C::workerModuleByteLimit,"budget_module_limit");
  total+=m.bytes.size();C::Require(total<=C::workerPackageByteLimit,"budget_package_limit");
  rows.push_back({{"name",m.name},{"mediaType",m.mediaType},{"bytes",m.bytes.size()},{"sha256",C::Hash(m.bytes)}});
 }
 std::sort(rows.begin(),rows.end(),[](const Json& a,const Json& b){return a.at("name")<b.at("name");});return rows;
}
std::vector<std::string> Services(){
 std::vector<std::string> result;for(const auto& f:family::v1::families())result.emplace_back(f.id);
 result.emplace_back("aggregate");result.emplace_back("team");return result;
}
std::string Wrapper(std::string_view id){
 detail::validateService(id);
 return "// Generated by the native shared MCP attempt-guard composer.\n"
  "import original from './mcp_original.js';\n"
  "import {withAttemptBudget} from './mcp_attempt_gate.js';\n"
  "export * from './mcp_original.js';\n"
  "export default withAttemptBudget(original,"+Json(id).dump()+");\n";
}

std::vector<Module> detail::wrap(std::string_view id,std::string_view main,
 const std::vector<Module>& ordinary,std::string_view adapter){
 validateService(id);(void)manifest(ordinary);
 C::Require(ordinary.size()<=30&&!adapter.empty()&&adapter.size()<=65536,"budget_adapter_or_source_count_invalid");
 C::Require(main!=guardOriginalModule&&main!=guardAdapterModule,"budget_already_wrapped_or_collision");
 bool found=false;std::vector<Module> modules;
 for(const auto& m:ordinary){
  C::Require(m.name!=guardOriginalModule&&m.name!=guardAdapterModule,"budget_already_wrapped_or_collision");
  if(m.name==main){
   C::Require(m.mediaType=="application/javascript+module","budget_main_type");found=true;
   modules.push_back({guardOriginalModule,m.mediaType,m.bytes});
   modules.push_back({m.name,m.mediaType,Wrapper(id)});
  }else modules.push_back(m);
 }
 C::Require(found,"budget_main_missing");
 modules.push_back({guardAdapterModule,"application/javascript+module",std::string(adapter)});
 (void)manifest(modules);return modules;
}
SourceGuardPackage ComposeSourceGuard(std::string_view id,std::string_view main,
 const std::vector<Module>& ordinary,std::string_view adapter){
 return {std::string(id),std::string(main),detail::wrap(id,main,ordinary,adapter),
  C::Hash(detail::manifest(ordinary).dump())};
}
